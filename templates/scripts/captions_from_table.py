"""Write compositions/captions.html from the measured caption table (one caption per line: `start_frame|text` or
`start_frame|text|baseline_px`). Each caption is a hard switch that lasts until the next one starts (the last until the
end). Sizes are in the project's NATIVE pixels (render the HyperFrames project at the reference's own resolution, so the
measured px apply 1:1). HyperFrames fetches Google Fonts by family name at render time.

Usage: python -I tools/captions_from_table.py captions.txt compositions/captions.html --w 720 --h 1280 --fps 30
        --duration 35 --font Poppins --weight 800 --size 51 --stroke 6 --baseline 917
Measure from the reference: font class, cap height (size ~ cap / 0.7), stroke, shadow, default baseline and the per-caption
exceptions, and the exact switch frame of every caption (difference the caption band frame to frame).
"""
import argparse, html

ap = argparse.ArgumentParser()
ap.add_argument("table"); ap.add_argument("out")
ap.add_argument("--w", type=int, default=1080); ap.add_argument("--h", type=int, default=1920)
ap.add_argument("--fps", type=float, default=30); ap.add_argument("--duration", type=float, required=True)
ap.add_argument("--font", default="Poppins"); ap.add_argument("--weight", type=int, default=800)
ap.add_argument("--size", type=float, default=51); ap.add_argument("--stroke", type=float, default=6)
ap.add_argument("--baseline", type=float, default=917, help="default baseline y in px")
ap.add_argument("--descent", type=float, default=0.22, help="baseline-to-box-bottom as a fraction of the font size")
a = ap.parse_args()

rows = []
for ln in open(a.table, encoding="utf-8"):
    ln = ln.strip()
    if not ln or ln.startswith("#"): continue
    parts = ln.split("|")
    rows.append((int(parts[0]), parts[1], float(parts[2]) if len(parts) > 2 and parts[2] else a.baseline))
rows.sort()
box = round(a.size * 1.2)
divs = []
for i, (f, text, base) in enumerate(rows):
    end = rows[i + 1][0] if i + 1 < len(rows) else round(a.duration * a.fps) + 1
    top = base + a.size * a.descent - box
    divs.append(f'    <div id="cap-{i:02d}" class="clip cap" data-start="{(f - 1) / a.fps:.6f}" data-duration="{(end - f) / a.fps:.6f}" '
                f'data-track-index="{2 + i % 2}" style="top:{top:.0f}px"><span>{html.escape(text)}</span></div>')
page = f"""<template>
  <style>
    #root {{ position: absolute; inset: 0; }}
    /* generated by tools/captions_from_table.py from the measured switch table */
    #root .cap {{ position: absolute; left: 0; right: 0; height: {box}px; display: flex; justify-content: center; align-items: flex-end; }}
    #root .cap span {{ font-family: "{a.font}", sans-serif; font-weight: {a.weight}; font-size: {a.size}px; line-height: 1; color: #fff;
      -webkit-text-stroke: {a.stroke}px #000; paint-order: stroke fill; letter-spacing: -0.3px;
      text-shadow: 0 3px 7px rgba(0,0,0,0.85), 0 1px 3px rgba(0,0,0,0.6); }}
  </style>
  <div id="root" data-composition-id="captions" data-width="{a.w}" data-height="{a.h}">
{chr(10).join(divs)}
  </div>
  <script>
    window.__timelines = window.__timelines || {{}};
    const tl = gsap.timeline({{ paused: true }});
    tl.set({{}}, {{}}, {a.duration});
    window.__timelines["captions"] = tl;
  </script>
</template>
"""
open(a.out, "w", encoding="utf-8").write(page)
print(f"{len(rows)} captions -> {a.out}")
